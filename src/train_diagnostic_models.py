def main() -> None:
    dataset_dir = resolve_dataset_dir()
    out_dir = Path(OUTPUT_DIR) if OUTPUT_DIR else dataset_dir / "outputs" / "model_training_v3_two_stage"
    out_dir.mkdir(parents=True, exist_ok=True)

    print("=== SI Diagnostic Model Training V3 Two-Stage Direct Run ===")
    print(f"Dataset directory : {dataset_dir.resolve()}")
    print(f"Output folder     : {out_dir.resolve()}")
    print(f"Holdout PN        : {HOLDOUT_PN}")
    print(f"Include golden    : {INCLUDE_GOLDEN}")
    print(f"Stage2 filter     : {'stage1 non-normal only' if STAGE2_ONLY_STAGE1_NON_NORMAL else 'all non-golden cases'}")

    df_raw, source_desc = load_v3_dataframe(dataset_dir)
    print(f"Source            : {source_desc}")
    print(f"Raw rows          : {len(df_raw):,}")
    print(f"Raw columns       : {len(df_raw.columns):,}")

    # Save a quick column inventory for traceability.
    pd.DataFrame({"column": list(df_raw.columns)}).to_csv(
        out_dir / "input_columns_v3.csv",
        index=False,
        encoding="utf-8-sig",
    )

    all_metrics: List[pd.DataFrame] = []
    bundle: Dict[str, object] = {
        "version": "v3_two_stage",
        "dataset_dir": str(dataset_dir),
        "source": source_desc,
        "holdout_pn": HOLDOUT_PN,
        "stage1_models": {},
        "stage2_model": None,
    }

    # ----------------------------
    # Stage 1: deviation heads
    # ----------------------------
    for target_col in STAGE1_TARGETS:
        if target_col not in df_raw.columns:
            print(f"[WARN] Stage-1 target missing and skipped: {target_col}")
            continue

        task_name = target_col
        metrics_df, best_infos = run_training_task(
            df_raw=df_raw,
            task_name=task_name,
            target_col=target_col,
            feature_selector=is_stage1_feature_name,
            preferred_label_order=STAGE1_STATUS_ORDER,
            display_label_map=STAGE1_DISPLAY_LABELS,
            out_dir=out_dir,
            seed=SEED,
        )
        if not metrics_df.empty:
            all_metrics.append(metrics_df)
        best = choose_best_for_bundle(best_infos)
        if best is not None:
            bundle["stage1_models"][target_col] = {
                "model": best["best_model"],
                "feature_cols": best["feature_cols"],
                "best_model_name": best["best_model_name"],
                "best_macro_f1": best["best_macro_f1"],
                "split": best["split_name"],
                "target_col": target_col,
                "label_order": STAGE1_STATUS_ORDER,
            }

    # ----------------------------
    # Stage 2: root-cause model
    # ----------------------------
    df_stage2 = df_raw.copy()
    if STAGE2_ONLY_STAGE1_NON_NORMAL and "stage1_overall_status" in df_stage2.columns:
        df_stage2 = df_stage2[df_stage2["stage1_overall_status"].astype(str) != "normal"].copy()

    if "label" in df_stage2.columns:
        metrics_df, best_infos = run_training_task(
            df_raw=df_stage2,
            task_name="stage2_root_cause",
            target_col="label",
            feature_selector=is_stage2_feature_name,
            preferred_label_order=STAGE2_LABEL_ORDER,
            display_label_map=STAGE2_DISPLAY_LABELS,
            out_dir=out_dir,
            seed=SEED,
        )
        if not metrics_df.empty:
            all_metrics.append(metrics_df)
        best = choose_best_for_bundle(best_infos)
        if best is not None:
            bundle["stage2_model"] = {
                "model": best["best_model"],
                "feature_cols": best["feature_cols"],
                "best_model_name": best["best_model_name"],
                "best_macro_f1": best["best_macro_f1"],
                "split": best["split_name"],
                "target_col": "label",
                "label_order": STAGE2_LABEL_ORDER,
            }
    else:
        print("[WARN] Stage-2 target 'label' not found; Stage 2 skipped.")

    if all_metrics:
        combined = pd.concat(all_metrics, ignore_index=True)
        combined_path = out_dir / "all_metrics_v3_two_stage.csv"
        combined.to_csv(combined_path, index=False, encoding="utf-8-sig")
        print("\n=== Metrics summary ===")
        cols = ["task", "split", "model", "accuracy", "macro_f1", "weighted_f1", "test_samples", "feature_count"]
        existing = [c for c in cols if c in combined.columns]
        print(combined[existing].to_string(index=False))
        print(f"[SAVED] {combined_path}")

    bundle_path = out_dir / "two_stage_model_bundle.pkl"
    with open(bundle_path, "wb") as f:
        pickle.dump(bundle, f)
    print(f"[SAVED] {bundle_path}")

    print("\nDone. Review metrics CSV files, confusion matrices, feature importance, and best_model_*.pkl files.")
    print("Suggested first files to inspect:")
    print(f"  {out_dir / 'all_metrics_v3_two_stage.csv'}")
    print(f"  {out_dir / 'stage1_overall_status'}")
    print(f"  {out_dir / 'stage2_root_cause'}")


if __name__ == "__main__":
    main()
