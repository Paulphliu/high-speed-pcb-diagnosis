def random_split_dataframe(df: pd.DataFrame, target_col: str, seed: int) -> Tuple[pd.DataFrame, pd.DataFrame]:
    y = df[target_col]
    counts = y.value_counts()
    stratify = y if len(counts) > 1 and counts.min() >= 2 else None
    train_df, test_df = train_test_split(
        df,
        test_size=0.20,
        random_state=seed,
        stratify=stratify,
    )
    return train_df.copy(), test_df.copy()


def pn_holdout_split_dataframe(df: pd.DataFrame, target_col: str, holdout_pn: str) -> Tuple[pd.DataFrame, pd.DataFrame]:
    train_df = df[df["PN_ID"] != holdout_pn].copy()
    test_df = df[df["PN_ID"] == holdout_pn].copy()

    if train_df.empty or test_df.empty:
        raise ValueError(f"Invalid holdout PN: {holdout_pn}. Train or test set is empty.")

    common_targets = sorted(set(train_df[target_col]).intersection(set(test_df[target_col])))
    train_df = train_df[train_df[target_col].isin(common_targets)].copy()
    test_df = test_df[test_df[target_col].isin(common_targets)].copy()

    # Keep only classes with enough samples in both train and test.
    train_counts = train_df[target_col].value_counts()
    test_counts = test_df[target_col].value_counts()
    valid = [
        c for c in common_targets
        if train_counts.get(c, 0) >= MIN_CLASS_COUNT and test_counts.get(c, 0) >= 1
    ]
    train_df = train_df[train_df[target_col].isin(valid)].copy()
    test_df = test_df[test_df[target_col].isin(valid)].copy()

    if train_df.empty or test_df.empty:
        raise ValueError(f"No common valid target classes between training set and holdout PN: {holdout_pn}")

    return train_df, test_df


def resolve_labels(y_true: pd.Series, y_pred: np.ndarray, preferred_order: List[str]) -> List[str]:
    present = set(y_true.astype(str).unique()).union(set(pd.Series(y_pred).astype(str).unique()))
    labels = [x for x in preferred_order if x in present]
    labels += sorted([x for x in present if x not in labels])
    return labels


def evaluate_model(
    name: str,
    model: Pipeline,
    X_test: pd.DataFrame,
    y_test: pd.Series,
    preferred_label_order: List[str],
) -> Tuple[Dict, pd.DataFrame, np.ndarray, List[str]]:
    y_pred = model.predict(X_test)
    labels = resolve_labels(y_test, y_pred, preferred_label_order)

    metrics = {
        "model": name,
        "accuracy": accuracy_score(y_test, y_pred),
        "macro_f1": f1_score(y_test, y_pred, average="macro", zero_division=0),
        "weighted_f1": f1_score(y_test, y_pred, average="weighted", zero_division=0),
        "test_samples": len(y_test),
        "class_count_test": y_test.nunique(),
    }

    report_dict = classification_report(
        y_test,
        y_pred,
        labels=labels,
        output_dict=True,
        zero_division=0,
    )
    report_df = pd.DataFrame(report_dict).T.reset_index().rename(columns={"index": "class"})
    cm = confusion_matrix(y_test, y_pred, labels=labels)
    return metrics, report_df, cm, labels


def plot_confusion_matrix(
    cm: np.ndarray,
    labels: List[str],
    title: str,
    out_path: Path,
    display_label_map: Dict[str, str],
) -> None:
    display_labels = [display_label_map.get(l, l) for l in labels]
    fig, ax = plt.subplots(figsize=(max(7, len(labels) * 1.2), max(6, len(labels) * 1.0)))
    im = ax.imshow(cm, interpolation="nearest")
    ax.set_title(title)
    fig.colorbar(im, ax=ax)

    ax.set_xticks(np.arange(len(labels)))
    ax.set_yticks(np.arange(len(labels)))
    ax.set_xticklabels(display_labels, rotation=35, ha="right")
    ax.set_yticklabels(display_labels)
    ax.set_ylabel("True label")
    ax.set_xlabel("Predicted label")

    threshold = cm.max() / 2 if cm.size and cm.max() > 0 else 0
    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            ax.text(
                j,
                i,
                format(int(cm[i, j]), "d"),
                ha="center",
                va="center",
                color="white" if cm[i, j] > threshold else "black",
                fontsize=9,
            )

    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=180)
    plt.close(fig)
    print(f"[SAVED] {out_path}")


def extract_feature_importance(model: Pipeline, feature_cols: List[str]) -> Optional[pd.DataFrame]:
    clf = model.named_steps["model"]
    if hasattr(clf, "feature_importances_"):
        importance = clf.feature_importances_
    elif hasattr(clf, "coef_"):
        coef = clf.coef_
        importance = np.mean(np.abs(coef), axis=0)
    else:
        return None

    if len(importance) != len(feature_cols):
        return None

    out = pd.DataFrame({"feature": feature_cols, "importance": importance})
    return out.sort_values("importance", ascending=False).reset_index(drop=True)


def plot_feature_importance(importance_df: pd.DataFrame, title: str, out_path: Path, top_n: int = 25) -> None:
    top = importance_df.head(top_n).iloc[::-1]
    fig, ax = plt.subplots(figsize=(10, 8))
    ax.barh(top["feature"], top["importance"])
    ax.set_title(title)
    ax.set_xlabel("Importance")
    ax.grid(True, axis="x", alpha=0.3)
    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=180)
    plt.close(fig)
    print(f"[SAVED] {out_path}")


