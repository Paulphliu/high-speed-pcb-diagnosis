"""
train_diagnostic_models.py

Direct-run two-stage training script for the V3 high-speed PCB
signal-integrity diagnostic dataset.

Designed for the V3 dataset generated by:
- generate_training_dataset.py
- build_training_database.py

V3 concept:
Stage 1: baseline/global deviation detection
    - deviation from theoretical target
    - deviation from PN / lot population baseline
    - output: normal / warning / out_of_spec / severe

Stage 2: shape-based abnormality diagnosis
    - TDR local spike/dip/area/width
    - S21 notch / ripple
    - return-loss and high-frequency loss shape
    - output: likely root-cause class

Default workflow:
1. Load view_two_stage_summary from SQLite if available.
2. Train Stage 1 status heads:
   - stage1_overall_status
   - stage1_impedance_status
   - stage1_loss_status
3. Train Stage 2 root-cause classifier using shape-aware features.
4. Evaluate by random split and PN holdout split.
5. Save metrics, classification reports, confusion matrices,
   feature importances, best model pickles, and a two-stage model bundle.

This is a direct-run version. You can press Run in VS Code.
Change parameters in the USER SETTINGS section below.
"""

