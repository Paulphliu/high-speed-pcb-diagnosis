def is_numeric_like(series: pd.Series) -> bool:
    if pd.api.types.is_numeric_dtype(series):
        return True
    converted = pd.to_numeric(series, errors="coerce")
    return converted.notna().mean() > 0.95


def select_feature_columns(df: pd.DataFrame, selector) -> List[str]:
    cols: List[str] = []
    for c in df.columns:
        if not selector(c):
            continue
        if is_numeric_like(df[c]):
            cols.append(c)
    return sorted(cols)


def clean_task_dataframe(
    df: pd.DataFrame,
    target_col: str,
    include_golden: bool,
    seed: int,
) -> pd.DataFrame:
    if target_col not in df.columns:
        raise ValueError(f"Missing target column: {target_col}")
    if "PN_ID" not in df.columns:
        raise ValueError("Data must include PN_ID.")

    data = df.copy()
    if not include_golden and "label" in data.columns:
        data = data[data["label"] != "golden_normal"].copy()

    data = data.dropna(subset=[target_col, "PN_ID"]).copy()
    data[target_col] = data[target_col].astype(str)

    # Drop rare target classes that cannot be split reliably.
    counts = data[target_col].value_counts()
    valid = counts[counts >= MIN_CLASS_COUNT].index.tolist()
    data = data[data[target_col].isin(valid)].copy()

    if MAX_ROWS_FOR_DEBUG is not None and len(data) > MAX_ROWS_FOR_DEBUG:
        classes = data[target_col].nunique()
        per_class = max(1, MAX_ROWS_FOR_DEBUG // max(classes, 1))
        data = (
            data.groupby(target_col, group_keys=False)
            .apply(lambda x: x.sample(min(len(x), per_class), random_state=seed))
            .reset_index(drop=True)
        )

    return data


def convert_features_to_numeric(df: pd.DataFrame, feature_cols: List[str]) -> Tuple[pd.DataFrame, List[str]]:
    data = df.copy()
    for c in feature_cols:
        data[c] = pd.to_numeric(data[c], errors="coerce")

    usable = [c for c in feature_cols if not data[c].isna().all()]
    dropped = [c for c in feature_cols if c not in usable]
    if dropped:
        print(f"[WARN] Dropped all-NaN features ({len(dropped)}): {dropped[:20]}{' ...' if len(dropped) > 20 else ''}")
    if not usable:
        raise ValueError("No usable numeric feature columns after conversion.")
    return data, usable


def summarize_feature_groups(feature_cols: List[str]) -> pd.DataFrame:
    rows = []
    for c in feature_cols:
        if "robust_z" in c:
            group = "pn_robust_z"
        elif "baseline_dev" in c:
            group = "pn_baseline_dev"
        elif "theory" in c:
            group = "theory_deviation"
        elif c.startswith("IL_slope"):
            group = "IL_slope"
        elif c.startswith("IL_"):
            group = "IL_frequency"
        elif c.startswith("DeltaL_slope"):
            group = "DeltaL_slope"
        elif c.startswith("DeltaL_"):
            group = "DeltaL_frequency"
        elif c.startswith("RL_"):
            group = "return_loss"
        elif c.startswith("Z_") or c.startswith("TDR_"):
            group = "TDR_impedance"
        elif c.startswith("notch_") or c.startswith("S21_ripple"):
            group = "notch_ripple"
        else:
            group = "other"
        rows.append({"feature": c, "group": group})
    return pd.DataFrame(rows)


