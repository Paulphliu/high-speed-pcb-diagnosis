def train_and_evaluate_split(
    task_name: str,
    target_col: str,
    split_name: str,
    train_df: pd.DataFrame,
    test_df: pd.DataFrame,
    feature_cols: List[str],
    preferred_label_order: List[str],
    display_label_map: Dict[str, str],
    out_dir: Path,
    seed: int,
) -> Tuple[pd.DataFrame, Dict]:
    X_train = train_df[feature_cols].copy()
    y_train = train_df[target_col].copy()
    X_test = test_df[feature_cols].copy()
    y_test = test_df[target_col].copy()

    estimators = build_models(seed)
    all_metrics = []
    best_info: Dict = {
        "task_name": task_name,
        "target_col": target_col,
        "split_name": split_name,
        "best_model_name": None,
        "best_model": None,
        "best_macro_f1": -1.0,
        "feature_cols": feature_cols,
    }

    task_dir = out_dir / task_name
    task_dir.mkdir(parents=True, exist_ok=True)

    for name, estimator in estimators.items():
        scale = name == "logistic_regression"
        model = make_pipeline(estimator, feature_cols, scale=scale)
        print(f"\n[TRAIN] {task_name} / {split_name} / {name}")
        model.fit(X_train, y_train)

        metrics, report_df, cm, labels = evaluate_model(
            name,
            model,
            X_test,
            y_test,
            preferred_label_order,
        )
        metrics.update({
            "task": task_name,
            "target": target_col,
            "split": split_name,
            "feature_count": len(feature_cols),
            "train_samples": len(train_df),
            "test_samples": len(test_df),
        })
        all_metrics.append(metrics)

        print(
            f"[RESULT] {task_name}/{split_name}/{name}: "
            f"accuracy={metrics['accuracy']:.4f}, "
            f"macro_f1={metrics['macro_f1']:.4f}, "
            f"weighted_f1={metrics['weighted_f1']:.4f}"
        )

        safe_name = f"{split_name}_{name}"
        report_path = task_dir / f"classification_report_{safe_name}.csv"
        report_df.to_csv(report_path, index=False, encoding="utf-8-sig")
        print(f"[SAVED] {report_path}")

        plot_confusion_matrix(
            cm,
            labels,
            title=f"{task_name} - {split_name} - {name}",
            out_path=task_dir / f"confusion_matrix_{safe_name}.png",
            display_label_map=display_label_map,
        )

        imp_df = extract_feature_importance(model, feature_cols)
        if imp_df is not None:
            imp_path = task_dir / f"feature_importance_{safe_name}.csv"
            imp_df.to_csv(imp_path, index=False, encoding="utf-8-sig")
            print(f"[SAVED] {imp_path}")
            plot_feature_importance(
                imp_df,
                title=f"{task_name} feature importance - {split_name} - {name}",
                out_path=task_dir / f"feature_importance_{safe_name}.png",
            )

        if metrics["macro_f1"] > best_info["best_macro_f1"]:
            best_info.update({
                "best_model_name": name,
                "best_model": model,
                "best_macro_f1": metrics["macro_f1"],
            })

    if best_info["best_model"] is not None:
        model_path = task_dir / f"best_model_{split_name}_{best_info['best_model_name']}.pkl"
        with open(model_path, "wb") as f:
            pickle.dump(
                {
                    "model": best_info["best_model"],
                    "task_name": task_name,
                    "target_col": target_col,
                    "feature_cols": feature_cols,
                    "best_model_name": best_info["best_model_name"],
                    "split": split_name,
                    "holdout_pn": HOLDOUT_PN if split_name.startswith("pn_holdout") else None,
                    "label_order": preferred_label_order,
                },
                f,
            )
        best_info["model_path"] = str(model_path)
        print(f"[SAVED] {model_path}")

    return pd.DataFrame(all_metrics), best_info


def run_training_task(
    df_raw: pd.DataFrame,
    task_name: str,
    target_col: str,
    feature_selector,
    preferred_label_order: List[str],
    display_label_map: Dict[str, str],
    out_dir: Path,
    seed: int,
) -> Tuple[pd.DataFrame, List[Dict]]:
    print("\n" + "=" * 72)
    print(f"TASK: {task_name}")
    print(f"Target column: {target_col}")

    df_task = clean_task_dataframe(df_raw, target_col=target_col, include_golden=INCLUDE_GOLDEN, seed=seed)
    if df_task.empty or df_task[target_col].nunique() < 2:
        print(f"[SKIP] {task_name}: fewer than 2 valid target classes.")
        return pd.DataFrame(), []

    feature_cols = select_feature_columns(df_task, feature_selector)
    df_task, feature_cols = convert_features_to_numeric(df_task, feature_cols)

    print(f"Rows             : {len(df_task):,}")
    print(f"Target classes   : {df_task[target_col].nunique():,}")
    print(f"Feature columns  : {len(feature_cols):,}")
    print("\nClass counts:")
    print(df_task[target_col].value_counts().to_string())
    print("\nPN counts:")
    print(df_task["PN_ID"].value_counts().sort_index().to_string())

    task_dir = out_dir / task_name
    task_dir.mkdir(parents=True, exist_ok=True)

    feature_df = summarize_feature_groups(feature_cols)
    feature_df.to_csv(task_dir / f"feature_columns_{task_name}.csv", index=False, encoding="utf-8-sig")
    df_task[target_col].value_counts().rename_axis(target_col).reset_index(name="count").to_csv(
        task_dir / f"class_counts_{task_name}.csv",
        index=False,
        encoding="utf-8-sig",
    )
    print("\nFeature group counts:")
    print(feature_df["group"].value_counts().to_string())
    print(f"[SAVED] {task_dir / f'feature_columns_{task_name}.csv'}")

    all_metrics: List[pd.DataFrame] = []
    best_infos: List[Dict] = []

    if RUN_RANDOM_SPLIT:
        train_df, test_df = random_split_dataframe(df_task, target_col=target_col, seed=seed)
        metrics_df, best = train_and_evaluate_split(
            task_name=task_name,
            target_col=target_col,
            split_name="random_split",
            train_df=train_df,
            test_df=test_df,
            feature_cols=feature_cols,
            preferred_label_order=preferred_label_order,
            display_label_map=display_label_map,
            out_dir=out_dir,
            seed=seed,
        )
        metrics_df.to_csv(task_dir / "random_split_metrics.csv", index=False, encoding="utf-8-sig")
        all_metrics.append(metrics_df)
        best_infos.append(best)

    if RUN_PN_HOLDOUT:
        if HOLDOUT_PN in set(df_task["PN_ID"]):
            try:
                train_df, test_df = pn_holdout_split_dataframe(df_task, target_col=target_col, holdout_pn=HOLDOUT_PN)
                metrics_df, best = train_and_evaluate_split(
                    task_name=task_name,
                    target_col=target_col,
                    split_name=f"pn_holdout_{HOLDOUT_PN}",
                    train_df=train_df,
                    test_df=test_df,
                    feature_cols=feature_cols,
                    preferred_label_order=preferred_label_order,
                    display_label_map=display_label_map,
                    out_dir=out_dir,
                    seed=seed,
                )
                metrics_df.to_csv(task_dir / "pn_holdout_metrics.csv", index=False, encoding="utf-8-sig")
                all_metrics.append(metrics_df)
                best_infos.append(best)
            except ValueError as exc:
                print(f"[WARN] PN holdout skipped for {task_name}: {exc}")
        else:
            print(f"[WARN] HOLDOUT_PN {HOLDOUT_PN} not found for {task_name}. Skipping PN holdout split.")

    combined = pd.concat(all_metrics, ignore_index=True) if all_metrics else pd.DataFrame()
    if not combined.empty:
        combined.to_csv(task_dir / f"all_metrics_{task_name}.csv", index=False, encoding="utf-8-sig")
        print(f"[SAVED] {task_dir / f'all_metrics_{task_name}.csv'}")

    return combined, best_infos


def choose_best_for_bundle(best_infos: List[Dict]) -> Optional[Dict]:
    if not best_infos:
        return None
    # Prefer PN holdout models when available; otherwise use best random split.
    holdout = [b for b in best_infos if str(b.get("split_name", "")).startswith("pn_holdout")]
    candidates = holdout if holdout else best_infos
    candidates = [b for b in candidates if b.get("best_model") is not None]
    if not candidates:
        return None
    return sorted(candidates, key=lambda x: x.get("best_macro_f1", -1.0), reverse=True)[0]


