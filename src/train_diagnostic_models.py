def is_stage1_feature_name(col: str) -> bool:
    """Features for global / baseline deviation detection."""
    if col in STAGE1_EXCLUDE_COLUMNS:
        return False

    include_tokens = [
        "target_dev",
        "theory_dev",
        "theory_excess_ratio",
        "pn_baseline_dev",
        "pn_robust_z",
        "pn_excess_ratio",
        "loss_baseline_excess_ratio",
    ]
    if any(token in col for token in include_tokens):
        return True

    # Raw measured global features are also allowed.
    if col.startswith(("IL_", "DeltaL_")):
        return True
    if col in {
        "Z_mean",
        "Z_max_dev",
        "TDR_peak_abs_ohm",
        "TDR_energy",
        "RL_min",
        "RL_mean",
        "RL_ripple",
    }:
        return True

    return False


def is_stage2_feature_name(col: str) -> bool:
    """Features for shape/root-cause diagnosis."""
    if col in STAGE2_EXCLUDE_COLUMNS:
        return False

    shape_prefixes = (
        "TDR_",
        "RL_",
        "notch_",
        "S21_ripple",
        "IL_",
        "DeltaL_",
        "Z_",
    )
    if col.startswith(shape_prefixes):
        return True

    shape_tokens = [
        "ripple",
        "slope",
        "peak",
        "dip",
        "energy",
        "local",
        "region",
        "baseline_dev",
        "robust_z",
    ]
    if any(token in col for token in shape_tokens):
        return True

    return False


