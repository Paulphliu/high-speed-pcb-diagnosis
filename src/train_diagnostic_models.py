def resolve_dataset_dir() -> Path:
    dataset_dir = Path(DATASET_DIR)
    if dataset_dir.exists():
        return dataset_dir

    if AUTO_FIND_DATASET:
        for candidate in DATASET_FALLBACKS:
            path = Path(candidate)
            if path.exists():
                return path

    raise FileNotFoundError(
        "Dataset directory not found.\n"
        f"Current DATASET_DIR = {DATASET_DIR!r}\n"
        "Please change DATASET_DIR in the USER SETTINGS section."
    )


def table_or_view_exists(conn: sqlite3.Connection, name: str) -> bool:
    row = conn.execute(
        "SELECT name FROM sqlite_master WHERE name=? AND type IN ('table', 'view');",
        (name,),
    ).fetchone()
    return row is not None


def resolve_data_source(dataset_dir: Path) -> Tuple[str, Optional[Path]]:
    if SOURCE == "csv":
        return "csv", None

    candidates: List[Path] = []
    if DB_NAME:
        candidates.append(dataset_dir / DB_NAME)
    for name in DB_NAME_CANDIDATES:
        path = dataset_dir / name
        if path not in candidates:
            candidates.append(path)
    candidates.extend(sorted(dataset_dir.glob("*.sqlite")))

    for db_path in candidates:
        if db_path.exists():
            if SOURCE in {"auto", "sqlite"}:
                return "sqlite", db_path

    if SOURCE == "sqlite":
        names = ", ".join(str(p) for p in candidates)
        raise FileNotFoundError(f"No SQLite DB found. Tried: {names}")

    return "csv", None


def read_sqlite_v3(db_path: Path) -> pd.DataFrame:
    with sqlite3.connect(db_path) as conn:
        if table_or_view_exists(conn, "view_two_stage_summary"):
            return pd.read_sql_query("SELECT * FROM view_two_stage_summary", conn)

        if not table_or_view_exists(conn, "si_fingerprint_features"):
            raise ValueError(f"SQLite DB missing si_fingerprint_features: {db_path}")

        base = pd.read_sql_query("SELECT * FROM si_fingerprint_features", conn)
        for table in ["si_stage1_deviation_features", "si_stage2_shape_features"]:
            if table_or_view_exists(conn, table):
                extra = pd.read_sql_query(f"SELECT * FROM {table}", conn)
                base = merge_without_duplicate_columns(base, extra, key="case_id")
        return base


def merge_without_duplicate_columns(left: pd.DataFrame, right: pd.DataFrame, key: str) -> pd.DataFrame:
    keep_cols = [key] + [c for c in right.columns if c != key and c not in left.columns]
    return left.merge(right[keep_cols], on=key, how="left")


def read_csv_v3(dataset_dir: Path) -> pd.DataFrame:
    feature_path = dataset_dir / "processed" / "si_fingerprint_features.csv"
    if not feature_path.exists():
        raise FileNotFoundError(f"Missing feature CSV: {feature_path}")

    df = pd.read_csv(feature_path)
    for csv_name in [
        "si_stage1_deviation_features.csv",
        "si_stage2_shape_features.csv",
    ]:
        path = dataset_dir / "processed" / csv_name
        if path.exists():
            extra = pd.read_csv(path)
            df = merge_without_duplicate_columns(df, extra, key="case_id")
    return df


def load_v3_dataframe(dataset_dir: Path) -> Tuple[pd.DataFrame, str]:
    source, db_path = resolve_data_source(dataset_dir)
    if source == "sqlite":
        assert db_path is not None
        return read_sqlite_v3(db_path), f"sqlite: {db_path}"
    return read_csv_v3(dataset_dir), f"csv: {dataset_dir / 'processed'}"


